#!/usr/bin/env python3
"""
Promote the selected v7 model and rule to the live configuration (docs/POLICY_V7.md §3.2, §4.3).

Reads reports/v7/training_v7.json (written by scripts/train_v7.py) and the HPA-tuned target from
reports/v7/calibration.json (scripts/analyze_v7_calibration.py), then writes:

* models/flexascale_v7/best_model/best_model.zip + model_card.json (observation version 3);
* config/apps/shopping_v7.yaml       the v7 policy (FlexaScale-RL and FlexaScale-Auto arms);
* config/apps/shopping_v7_rule.yaml  the selected rule instead of the model (attribution arm);
* config/lab.yaml                    variants v7 / v7_rule and the hpa_tuned defaults;
* reports/v7/arms.json               the five arms for scripts/v7_plan.py evaluation.

Nothing here looks at live evaluation results; it only copies choices already made.

    python scripts/promote_v7.py
"""

import argparse
import json
import re
import shutil
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from flexascale.rl import features_v3 as fv  # noqa: E402
from flexascale.simulator.twin_control import V7_GUARDS  # noqa: E402
from flexascale.simulator.twin_env import ACTION_DELTAS, N_MAX, RewardConfig  # noqa: E402

POLICY_HEADER = """# FlexaScale application policy: the shop with the v7 graph policy (docs/POLICY_V7.md §4).
# Generated by scripts/promote_v7.py from config/apps/shopping.yaml; only the controller settings differ.
# Guards match the twin the policy was trained in (simulator/twin_control.V7_GUARDS):
#   up to +3 replicas per decision, 20 s between scale-ups, one replica down per 30 s, never scale down a pod at
#   >= 80% of its 500m CPU limit (400% of request). No single latency SLO: v7 reads each service's latency
#   relative to its own low-load latency. The confidence gate is off (thresholds 0): v7 was trained without one,
#   its action probabilities are not calibrated confidences, and a gate would hand services to HPA in the
#   RL-only arm. Health fallback (missing/stale telemetry, lost Lease, operator error) still returns a service
#   to native HPA.
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--training", default=str(ROOT / "reports" / "v7" / "training_v7.json"))
    ap.add_argument("--calibration", default=str(ROOT / "reports" / "v7" / "calibration.json"))
    ap.add_argument("--hpa-target", type=int, help="override (only before a calibration result exists)")
    args = ap.parse_args()

    tr = json.loads(Path(args.training).read_text())
    run = tr.get("selected")
    if not run:
        print("no selected model in", args.training)
        return 1
    rule_name = tr["selected_rule"]
    t, d = (float(x) for x in re.match(r"limit_target\(([\d.]+)/([\d.]+)\)", rule_name).groups())
    if args.hpa_target:
        target = args.hpa_target
    else:
        target = json.loads(Path(args.calibration).read_text())["selected_cpu_target_pct"]

    src = ROOT / "models" / "flexascale_v7" / run / "best_model.zip"
    dst_dir = ROOT / "models" / "flexascale_v7" / "best_model"
    dst_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst_dir / "best_model.zip")
    runs = tr["runs"]
    card = {
        "name": "flexascale_v7",
        "created": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "selected_run": run,
        "source_checkpoint": str(src.relative_to(ROOT)),
        "observation": {"version": fv.OBSERVATION_VERSION, "n_max": N_MAX, "per_service_fields": list(fv.FEATURES),
                        "low": fv.LOW.tolist(), "high": fv.HIGH.tolist(), "max_replicas": 10,
                        "units": "see src/flexascale/rl/features_v3.py", "graph": "the application's call graph (policy topology)"},
        "action": {"deltas": list(ACTION_DELTAS)},
        "policy": ({"class": "stable_baselines3 ActorCriticPolicy + flexascale.rl.graph_policy.GraphFocalExtractor",
                    "decision": "focal (one row per service: the application + a one-hot of the service)"}
                   if runs[run].get("design") == "focal" else
                   {"class": "flexascale.rl.graph_policy.GraphPolicy", "decision": "joint (all services in one output)"})
                  | {"hidden": 64, "rounds": 2, "use_graph": runs[run]["use_graph"]},
        "training": {"simulator": "application twin (config/twin/shopping.json, src/flexascale/simulator/twin*.py)",
                     "reward": {**RewardConfig().__dict__}, "guards": V7_GUARDS.__dict__,
                     "runs": {k: {kk: v.get(kk) for kk in ("design", "use_graph", "reward", "seed", "steps", "minutes", "best", "paused_at")}
                              for k, v in runs.items()}},
        "validation": runs[run].get("best"),
        "protocol": "docs/POLICY_V7.md §4.3",
    }
    text = json.dumps(card, indent=1, default=str) + "\n"
    (dst_dir / "model_card.json").write_text(text)
    (dst_dir.parent / "model_card.json").write_text(text)  # where the dashboard's Models page and Dockerfile look

    base = yaml.safe_load((ROOT / "config" / "apps" / "shopping.yaml").read_text())
    pol = dict(base)
    pol.update({
        "max_step": V7_GUARDS.max_step, "max_scale_down_step": V7_GUARDS.max_scale_down_step,
        "scale_down_block_cpu_pct": V7_GUARDS.scale_down_block_cpu_pct, "slo_latency_ms": None,
        "confidence_threshold": 0.0, "deactivation_threshold": 0.0,
        "scale_up_cooldown_seconds": V7_GUARDS.scale_up_cooldown_s, "scale_down_cooldown_seconds": V7_GUARDS.scale_down_cooldown_s,
        "model_path": "models/flexascale_v7/best_model/best_model.zip",
        "auto": {"sla_latency_ratio": 1.0, "cpu_risk_pct": V7_GUARDS.scale_down_block_cpu_pct, "dwell_steps": 2,
                 "hpa_target_pct": float(target)},
    })
    out = ROOT / "config" / "apps" / "shopping_v7.yaml"
    out.write_text(POLICY_HEADER + yaml.safe_dump(pol, sort_keys=False, default_flow_style=None))
    rule = dict(pol)
    rule["controller_rule"] = {"type": "limit_target", "target": t, "down": d}
    (ROOT / "config" / "apps" / "shopping_v7_rule.yaml").write_text(
        POLICY_HEADER.replace("the v7 graph policy", f"the hand-written rule {rule_name} instead of a model (attribution arm)")
        + yaml.safe_dump(rule, sort_keys=False, default_flow_style=None))

    lab_path = ROOT / "config" / "lab.yaml"
    text = lab_path.read_text()
    if "variants:" not in text:
        text = text.replace("    policy: config/apps/shopping.yaml\n",
                            "    policy: config/apps/shopping.yaml\n    variants:                                  # docs/POLICY_V7.md §3.2\n"
                            "      v7: config/apps/shopping_v7.yaml\n      v7_rule: config/apps/shopping_v7_rule.yaml\n", 1)
    text = re.sub(r"\nhpa_tuned:.*\n", "\n", text)
    text = re.sub(r"^(e2e_p95_slo_ms: 1000.*)$", lambda m: m.group(1) + f"\nhpa_tuned: {{cpu_target_pct: {target}, scale_down_window_s: 60}}"
                  "              # docs/POLICY_V7.md §2.1 calibration", text, count=1, flags=re.M)
    lab_path.write_text(text)

    hpa_fields = {"hpa_cpu_target_pct": target, "hpa_scale_down_window_s": 60}
    arms = {"hpa_default": {"controller": "hpa"},
            "hpa_tuned": {"controller": "hpa_tuned", **hpa_fields},
            "rl": {"controller": "flexascale", "policy_variant": "v7", **hpa_fields},
            "auto": {"controller": "auto", "policy_variant": "v7", **hpa_fields},
            "heuristic": {"controller": "flexascale", "policy_variant": "v7_rule", **hpa_fields}}
    (ROOT / "reports" / "v7" / "arms.json").write_text(json.dumps(arms, indent=1) + "\n")
    print(f"promoted {run} -> {dst_dir}; rule {rule_name}; HPA-tuned target {target}%; wrote shopping_v7*.yaml, lab.yaml, arms.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""
Promote the v9 choices to the live configuration (docs/POLICY_V9.md §5, §6). Copies decisions already
made; looks at no live evaluation result.

Reads reports/v9/gate.json (scripts/v9_gate.py), reports/v9/training_v7.json and reports/v9/calibration.json
(HPA-tuned's target on this laptop), then writes:

* models/flexascale_v9/best_model/ + model_card.json  if the gate passed (otherwise the RL arm keeps v7's model);
* config/apps/shopping_v9.yaml   the RL arm: v7's operator guards, the gate's model, Auto's HPA target = HPA-tuned's;
* config/lab.yaml                variant v9 and the hpa_tuned default of this laptop;
* reports/v9/arms.json           the four pre-registered arms (scripts/v9_plan.py evaluation);
* with --set-default: config/apps/shopping.yaml becomes the RL arm's policy (the previous default is kept as
  config/apps/shopping_v5.yaml and stays selectable as variant v5).

    python scripts/promote_v9.py [--set-default]
"""

import argparse
import json
import re
import shutil
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gate", default=str(ROOT / "reports" / "v9" / "gate.json"))
    ap.add_argument("--training", default=str(ROOT / "reports" / "v9" / "training_v7.json"))
    ap.add_argument("--calibration", default=str(ROOT / "reports" / "v9" / "calibration.json"))
    ap.add_argument("--set-default", action="store_true")
    args = ap.parse_args()

    from flexascale.rl import features_v3 as fv
    from flexascale.simulator.twin_control import V7_GUARDS
    from flexascale.simulator.twin_env import ACTION_DELTAS, N_MAX, RewardConfig

    gate = json.loads(Path(args.gate).read_text(encoding="utf-8"))
    tr = json.loads(Path(args.training).read_text(encoding="utf-8"))
    target = int(json.loads(Path(args.calibration).read_text(encoding="utf-8"))["selected_cpu_target_pct"])
    model_rel = gate["rl_arm_model"]
    if gate["passed"]:
        run = tr["selected"]
        dst = ROOT / "models" / "flexascale_v9" / "best_model"
        dst.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / model_rel, dst / "best_model.zip")
        card = {
            "name": "flexascale_v9", "created": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "selected_run": run,
            "source_checkpoint": model_rel,
            "observation": {"version": fv.OBSERVATION_VERSION, "n_max": N_MAX, "per_service_fields": list(fv.FEATURES),
                            "low": fv.LOW.tolist(), "high": fv.HIGH.tolist(), "max_replicas": 10,
                            "units": "see src/flexascale/rl/features_v3.py", "graph": "the application's call graph (policy topology)"},
            "action": {"deltas": list(ACTION_DELTAS)},
            "policy": {"class": "stable_baselines3 ActorCriticPolicy + flexascale.rl.graph_policy.GraphFocalExtractor",
                       "decision": "focal (one row per service: the application + a one-hot of the service)",
                       "hidden": 64, "rounds": 2, "use_graph": tr["runs"][run].get("use_graph")},
            "training": {"simulator": "application twin fitted to the second laptop (config/twin/shopping_v9.json)",
                         "reward": {**RewardConfig().__dict__}, "guards": V7_GUARDS.__dict__, "device": tr.get("device"),
                         "runs": {k: {kk: v.get(kk) for kk in ("design", "use_graph", "reward", "seed", "steps", "minutes", "best")}
                                  for k, v in tr["runs"].items()}},
            "validation": tr["runs"][run].get("best"), "gate": {k: gate[k] for k in ("passed", "candidates")},
            "protocol": "docs/POLICY_V9.md §5",
        }
        text = json.dumps(card, indent=1, default=str) + "\n"
        (dst / "model_card.json").write_text(text, encoding="utf-8")
        (dst.parent / "model_card.json").write_text(text, encoding="utf-8")
        model_path = "models/flexascale_v9/best_model/best_model.zip"
    else:
        model_path = model_rel.replace("\\", "/")

    pol = yaml.safe_load((ROOT / "config" / "apps" / "shopping_v7.yaml").read_text(encoding="utf-8"))
    pol["model_path"] = model_path
    pol["label_selector"] = "app.kubernetes.io/part-of=flexascale-ecommerce"
    pol["auto"] = {**(pol.get("auto") or {}), "hpa_target_pct": float(target)}
    header = (f"# FlexaScale application policy for the second laptop (docs/POLICY_V9.md §5): the RL arm of the v9 evaluation.\n"
              f"# Generated by scripts/promote_v9.py. Model: {model_path} ({'v9, gate passed' if gate['passed'] else 'v7, the v9 gate was not passed'}).\n"
              f"# Operator guards as v7 (simulator/twin_control.V7_GUARDS); Auto hands services back to HPA at the calibrated "
              f"{target}% CPU target.\n")
    text = header + yaml.safe_dump(pol, sort_keys=False, default_flow_style=None)
    (ROOT / "config" / "apps" / "shopping_v9.yaml").write_text(text, encoding="utf-8")

    lab_path = ROOT / "config" / "lab.yaml"
    lab = lab_path.read_text(encoding="utf-8")
    if "      v9: config/apps/shopping_v9.yaml" not in lab:
        lab = lab.replace("      v7: config/apps/shopping_v7.yaml\n",
                          "      v7: config/apps/shopping_v7.yaml\n      v9: config/apps/shopping_v9.yaml                     # docs/POLICY_V9.md §5\n", 1)
    lab = re.sub(r"^hpa_tuned: .*$", f"hpa_tuned: {{cpu_target_pct: {target}, scale_down_window_s: 60}}              "
                 "# docs/POLICY_V9.md §3 calibration (second laptop)", lab, count=1, flags=re.M)
    if args.set_default:
        apps = ROOT / "config" / "apps"
        if not (apps / "shopping_v5.yaml").exists():
            shutil.copy2(apps / "shopping.yaml", apps / "shopping_v5.yaml")
        if "      v5: config/apps/shopping_v5.yaml" not in lab:
            lab = lab.replace("      v9: config/apps/shopping_v9.yaml", "      v5: config/apps/shopping_v5.yaml                     "
                              "# the earlier default (v5)\n      v9: config/apps/shopping_v9.yaml", 1)
        (apps / "shopping.yaml").write_text(text.replace("the RL arm of the v9 evaluation", "the default policy (= the v9 RL arm)"),
                                            encoding="utf-8")
    lab_path.write_text(lab, encoding="utf-8")

    hpa = {"hpa_cpu_target_pct": target, "hpa_scale_down_window_s": 60}
    arms = {"hpa_default": {"controller": "hpa"},
            "hpa_tuned": {"controller": "hpa_tuned", **hpa},
            "rl": {"controller": "flexascale", "policy_variant": "v9", **hpa},
            "auto": {"controller": "auto", "policy_variant": "v9", **hpa}}
    (ROOT / "reports" / "v9" / "arms.json").write_text(json.dumps(arms, indent=1) + "\n", encoding="utf-8")
    print(f"RL arm model {model_path}; HPA-tuned {target}%; wrote shopping_v9.yaml, lab.yaml, reports/v9/arms.json"
          + ("; default policy switched" if args.set_default else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
